export type ComplianceProfile = 'eu-enterprise' | 'us-fedramp' | 'global-startup' | 'personal';

export interface AITool {
  id: string;
  name: string;
  provider: string;
  logo: string;
  category: string;
  verified: boolean;
  performance: {
    accuracy: number;
    latency: number; // ms
    throughput: number;
  };
  trust: {
    dataSovereignty: 'EU' | 'US' | 'Global';
    trainingPrivacy: 'Never' | 'Opt-out' | 'Opt-in';
    sso: boolean;
    soc2: boolean;
    hipaa: boolean;
    encryptionAtRest: boolean;
  };
  costPerMToken: number;
  trendData: number[];
  policyUrl: string;
  lastUpdated: string;
}

